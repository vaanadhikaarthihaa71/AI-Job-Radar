-- ============================================================================
-- JOB RADAR - SUPABASE POSTGRES SCHEMA
-- ============================================================================

-- 1. Create JOBS Table
CREATE TABLE IF NOT EXISTS public.jobs (
    id TEXT PRIMARY KEY,                            -- SHA-256 hash of source + external_id/url
    title TEXT NOT NULL,
    company TEXT NOT NULL,
    location TEXT,
    is_remote BOOLEAN DEFAULT FALSE,
    posted_at TIMESTAMPTZ,                         -- Original posted date from job portal
    detected_at TIMESTAMPTZ DEFAULT NOW() NOT NULL, -- First detected timestamp (never overwritten on upsert)
    job_url TEXT NOT NULL,
    source TEXT NOT NULL,                           -- e.g. linkedin, indeed, glassdoor
    description TEXT,
    score INT DEFAULT 0,
    matched_skills TEXT[] DEFAULT '{}',
    seniority TEXT                                  -- e.g. Entry Level, Mid, Senior, Executive
);

-- Index for real-time querying & sorting
CREATE INDEX IF NOT EXISTS idx_jobs_score ON public.jobs (score DESC);
CREATE INDEX IF NOT EXISTS idx_jobs_detected_at ON public.jobs (detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_jobs_source ON public.jobs (source);

-- 2. Create COMPANIES_WATCHLIST Table
CREATE TABLE IF NOT EXISTS public.companies_watchlist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    ats_type TEXT NOT NULL,                         -- e.g. greenhouse, lever, workday
    ats_slug TEXT NOT NULL,                         -- e.g. stripe, Airbnb
    active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 3. Row Level Security (RLS) Policies
-- Enable RLS on both tables
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.companies_watchlist ENABLE ROW LEVEL SECURITY;

-- Allow anonymous & authenticated users to SELECT (Read-Only UI access)
CREATE POLICY "Allow anonymous read access on jobs"
    ON public.jobs
    FOR SELECT
    TO anon, authenticated
    USING (true);

CREATE POLICY "Allow anonymous read access on companies_watchlist"
    ON public.companies_watchlist
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- Service Role (backend crawler) bypasses RLS automatically in Supabase,
-- but explicit policies ensure service_role has full write capabilities:
CREATE POLICY "Allow service_role insert/update on jobs"
    ON public.jobs
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow service_role insert/update on companies_watchlist"
    ON public.companies_watchlist
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- 4. Realtime Subscription Setup
-- Add jobs table to the supabase_realtime publication
ALTER PUBLICATION supabase_realtime ADD TABLE public.jobs;
